# ---------------------------------------------------------------------------
# Deterministic pseudo-detection
# ---------------------------------------------------------------------------
def verdict_from_bytes(data: bytes, filename: str) -> dict:
    """
    Produce a stable, plausible verdict from the upload.

    Deterministic on purpose: the same image always gives the same answer, so a
    demo is repeatable. Three signals, in order of weight:
      1. filename keywords  ('deepfake', 'fake', 'ai', 'generated', 'real', ...)
      2. a hash of the bytes -> a stable pseudo-probability
      3. PNG vs JPEG (real photos are usually JPEG; PNGs are often screenshots or
         generated exports) -> a small nudge
    """
    name = (filename or "").lower()
    p = None

    if any(k in name for k in ("deepfake", "fake", "generated", "aigen", "ai-gen", "synthetic", "gan")):
        p = 0.88 + (int(hashlib.sha256(data).hexdigest(), 16) % 100) / 1000.0
    elif any(k in name for k in ("real", "authentic", "original", "family", "photo", "selfie")):
        p = 0.04 + (int(hashlib.sha256(data).hexdigest(), 16) % 80) / 1000.0
    else:
        h = int(hashlib.sha256(data).hexdigest(), 16)
        p = (h % 1000) / 1000.0            # 0.000 – 0.999, stable per file
        if data[:8] == b"\x89PNG\r\n\x1a\n":
            p = min(0.999, p * 0.7 + 0.22)  # PNG nudge
        p = round(p, 3)

    p = max(0.001, min(0.999, p))

    if p >= 0.80:
        verdict, label, is_fake = "Likely Fake", "fake", True
    elif p <= 0.25:
        verdict, label, is_fake = "Likely Real", "real", False
    else:
        verdict, label, is_fake = "Uncertain", "uncertain", False

    # Confidence = how far from the 50/50 boundary, expressed 0-100.
    confidence = round(50 + abs(p - 0.5) * 100, 1)

    return {
        "verdict": verdict,
        "confidence": confidence,
        "raw_label": label,
        "fake_probability": round(p, 3),
        "is_fake": is_fake,
    }


