# ---------------------------------------------------------------------------
# Rate limiter (so you can demo the Part C.3 cooldown)
# ---------------------------------------------------------------------------
class RateLimiter:
    def __init__(self, limit: int, window: float):
        self.limit, self.window = limit, window
        self.hits: deque[float] = deque()
        self.lock = threading.Lock()

    def allow(self) -> tuple[bool, int]:
        now = time.time()
        with self.lock:
            while self.hits and now - self.hits[0] > self.window:
                self.hits.popleft()
            if len(self.hits) >= self.limit:
                return False, int(self.window - (now - self.hits[0])) + 1
            self.hits.append(now)
            return True, 0


LIMITER = RateLimiter(limit=6, window=10.0)

# ---------------------------------------------------------------------------
# Multipart parsing (only what we need: pull out the first file part)
# ---------------------------------------------------------------------------
def parse_multipart(body: bytes, content_type: str) -> tuple[bytes, str, str]:
    m = re.search(r'boundary="?([^";]+)"?', content_type)
    if not m:
        return b"", "", ""
    boundary = ("--" + m.group(1)).encode()
    for part in body.split(boundary):
        part = part.strip(b"\r\n")
        if not part or part == b"--":
            continue
        head, _, payload = part.partition(b"\r\n\r\n")
        header_text = head.decode("utf-8", "replace")
        if 'name="file"' not in header_text:
            continue
        fn = re.search(r'filename="([^"]*)"', header_text)
        ct = re.search(r"Content-Type:\s*([^\r\n;]+)", header_text, re.I)
        return payload, (fn.group(1) if fn else "upload"), (ct.group(1) if ct else "")
    return b"", "", ""


MAX_IMAGE_BYTES = 8 * 1024 * 1024
ALLOWED_TYPES = {"image/jpeg", "image/png", "image/webp"}

CONFIG = {"latency": 1.0, "origin": "*"}


class Handler(BaseHTTPRequestHandler):
    server_version = "TruthGuardMock/1.0"
    protocol_version = "HTTP/1.1"

    # ---- plumbing ---------------------------------------------------------
    def log_message(self, fmt, *a):  # quieter, but still informative
        print(f"  {self.command} {self.path} -> {fmt % a}", flush=True)

    def _cors(self):
        self.send_header("Access-Control-Allow-Origin", CONFIG["origin"])
        self.send_header("Access-Control-Allow-Methods", "GET, POST, OPTIONS")
        self.send_header("Access-Control-Allow-Headers", "Authorization, Content-Type, X-Mock-Status")
        self.send_header("Access-Control-Max-Age", "600")
        self.send_header("Vary", "Origin")

    def _send(self, status: int, payload: dict | str, ctype: str = "application/json"):
        body = payload if isinstance(payload, bytes) else json.dumps(payload).encode()
        self.send_response(status)
        self._cors()
        self.send_header("Content-Type", ctype)
        self.send_header("Content-Length", str(len(body)))
        self.send_header("Cache-Control", "no-store")
        self.end_headers()
        self.wfile.write(body)

    def _error(self, status: int, detail: str, code: str):
        self._send(status, {"detail": detail, "error_code": code})

    def do_OPTIONS(self):
        self.send_response(204)
        self._cors()
        self.send_header("Content-Length", "0")
        self.end_headers()

    # ---- forced-error hook for demoing the frontend's error handling -------
    def _forced_status(self) -> int | None:
        raw = self.headers.get("X-Mock-Status")
        try:
            return int(raw) if raw else None
        except ValueError:
            return None

    FORCED = {
        429: ("Too many requests. Please wait a moment before trying again.", "rate_limited"),
        413: ("Image exceeds the 8 MB limit.", "payload_too_large"),
        502: ("Upstream model gateway error.", "bad_gateway"),
        503: ("Detection service temporarily unavailable.", "service_unavailable"),
        504: ("Model inference timed out.", "gateway_timeout"),
        401: ("Authentication required.", "missing_token"),
    }

    def _maybe_forced(self) -> bool:
        st = self._forced_status()
        if st is None:
            return False
        detail, code = self.FORCED.get(st, (f"Forced mock error {st}.", f"http_{st}"))
        if st == 429:
            self.send_response(st)
            self._cors()
            self.send_header("Retry-After", "10")
            self.send_header("Content-Type", "application/json")
            body = json.dumps({"detail": detail, "error_code": code}).encode()
            self.send_header("Content-Length", str(len(body)))
            self.end_headers()
            self.wfile.write(body)
        else:
            self._error(st, detail, code)
        return True

    # ---- routes ------------------------------------------------------------
    def do_GET(self):
        if self.path.startswith("/health"):
            self._send(200, {
                "status": "ok",
                "services": {
                    "detection": "mock-ready",
                    "fact_check": "mock-ready",
                    "note": "mock_backend.py — no model is loaded",
                },
            })
            return
        if self.path in ("/", "/docs"):
            self._send(200, MOCK_HTML, "text/html; charset=utf-8")
            return
        self._error(404, "Not found. Try /health, /api/v1/detect-image or /api/v1/fact-check.", "not_found")

    def do_POST(self):
        if self._maybe_forced():
            return

        # ---- rate limit ----
        ok, retry = LIMITER.allow()
        if not ok:
            self.send_response(429)
            self._cors()
            self.send_header("Retry-After", str(retry))
            self.send_header("Content-Type", "application/json")
            body = json.dumps({
                "detail": f"Too many requests. Please wait a moment before trying again ({retry}s).",
                "error_code": "rate_limited",
            }).encode()
            self.send_header("Content-Length", str(len(body)))
            self.end_headers()
            self.wfile.write(body)
            return

        length = int(self.headers.get("Content-Length") or 0)
        body = self.rfile.read(length) if length else b""

        # ---- detect-image ----
        if self.path.startswith("/api/v1/detect-image"):
            ctype = self.headers.get("Content-Type", "")
            if "multipart/form-data" not in ctype:
                return self._error(415, "Expected multipart/form-data with a field named 'file'.",
                                   "unsupported_media_type")

            data, filename, file_ctype = parse_multipart(body, ctype)
            if not data:
                return self._error(422, "No file part named 'file' was found in the request.",
                                   "missing_file_field")
            if file_ctype and file_ctype not in ALLOWED_TYPES:
                return self._error(415, f"Unsupported media type '{file_ctype}'. Allowed: jpg, png, webp.",
                                   "unsupported_media_type")
            if len(data) > MAX_IMAGE_BYTES:
                return self._error(413, "Image exceeds the 8 MB limit.", "payload_too_large")
            if not data:
                return self._error(400, "Uploaded file is empty.", "empty_file")

            started = time.perf_counter()
            time.sleep(CONFIG["latency"] + (len(data) % 700) / 1000.0)  # 1.0 – 1.7 s, looks real
            result = verdict_from_bytes(data, filename)
            result["analyzed_in_ms"] = int((time.perf_counter() - started) * 1000)
            result["_mock"] = True
            result["_disclaimer"] = DISCLAIMER
            print(f"    [mock] file={filename!r} bytes={len(data)} -> {result['verdict']} "
                  f"({result['confidence']}%)", flush=True)
            return self._send(200, result)

        # ---- fact-check ----
        if self.path.startswith("/api/v1/fact-check"):
            ctype = self.headers.get("Content-Type", "")
            if "application/json" not in ctype:
                return self._error(415, "Expected application/json.", "unsupported_media_type")
            try:
                payload = json.loads(body or b"{}")
            except json.JSONDecodeError:
                return self._error(400, "Request body is not valid JSON.", "invalid_json")

            claim = payload.get("claim")
            if not isinstance(claim, str):
                return self._error(422, "Field 'claim' must be a string.", "validation_error")
            claim = claim.strip()
            if len(claim) < 10:
                return self._error(422, f"Claim is too short ({len(claim)} chars); minimum is 10.",
                                   "validation_error")
            if len(claim) > 1000:
                return self._error(422, f"Claim is too long ({len(claim)} chars); maximum is 1000.",
                                   "validation_error")

            started = time.perf_counter()
            time.sleep(CONFIG["latency"] * 1.4)
            out = check_claim(claim)
            out["retrieved_context"] = [
                {"text": f"(mock) retrieved passage matching: {claim[:90]}", "score": 0.87},
                {"text": "(mock) second passage providing corroborating detail.", "score": 0.74},
            ]
            out["checked_in_ms"] = int((time.perf_counter() - started) * 1000)
            out["_mock"] = True
            out["_disclaimer"] = DISCLAIMER
            print(f"    [mock] claim={claim[:60]!r} -> {out['verdict']}", flush=True)
            return self._send(200, out)

        self._error(404, "Unknown endpoint.", "not_found")


